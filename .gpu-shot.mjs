import { chromium } from "@playwright/test";
const out = process.argv[2];
const prefix = process.argv[3] || "gpu";
const b = await chromium.launch({ args: ["--use-angle=d3d11", "--enable-gpu", "--ignore-gpu-blocklist"] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto("http://localhost:3000/");
await p.waitForSelector("[data-stage=ready]");
await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/${prefix}-hero.png` });
await p.screenshot({ path: `${out}/${prefix}-hero-zoom.png`, clip: { x: 470, y: 0, width: 500, height: 320 } });
await p.evaluate(() => window.scrollTo({ top: document.documentElement.scrollHeight, behavior: "instant" }));
await p.waitForTimeout(2000);
await p.screenshot({ path: `${out}/${prefix}-end.png` });
await b.close();
