import { chromium } from "@playwright/test";
const b = await chromium.launch({ args: ["--use-angle=d3d11", "--enable-gpu", "--ignore-gpu-blocklist"] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto("http://localhost:3000/");
await p.waitForSelector("[data-stage=ready]");
await p.evaluate(() => window.scrollTo({ top: document.documentElement.scrollHeight, behavior: "instant" }));
await p.waitForTimeout(2500);
const r = await p.locator("[data-core-anchor]").boundingBox();
console.log(JSON.stringify(r));
await p.addStyleTag({ content: "main, nav, aside, header, footer, [data-hud], a[href='#main'] { visibility: hidden !important } body > div:not([data-stage]):not(.sky-gradient) { visibility:hidden !important }" });
await p.waitForTimeout(300);
await p.screenshot({ path: process.argv[2] });
await b.close();
